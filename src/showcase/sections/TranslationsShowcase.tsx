const LOCALE_KEYS = ['en::FORMAL', 'de::FORMAL', 'de::INFORMAL'];
const LOCALES = LOCALE_KEYS.map(toTranslatableLocale);
const FIELDS = ['title', 'body'] as const;

interface TranslatedValues {
  translations: { title: Record<string, string>; body: Record<string, string> };
}

const renderEditor = ({ id, value, onChange, disabled }: { id?: string; value: string; onChange: (value: string) => void; disabled?: boolean }) => (
  <Textarea id={id} value={value} onChange={event => onChange(event.target.value)} disabled={disabled} rows={4} />
);

const BoundFields = () => {
  // delta saves: only the changed keys travel, so texts stored meanwhile (a background translation) survive the save
  const tabs = useEntityTranslations({ fields: FIELDS, locales: LOCALE_KEYS, defaultLocale: 'en::FORMAL', translationSaveMode: 'delta' });
  const form = useForm<TranslatedValues>({
    defaultValues: { translations: { title: { 'en::FORMAL': 'Hello' }, body: { 'en::FORMAL': 'Some **markdown**.' } } },
  });
  return (
    <Form form={form} onSubmit={() => {}} className="w-full space-y-4">
      <FormTranslatableInput<TranslatedValues> name="translations.title" label="Title (bound)" tabs={tabs} />
      <FormTranslatableMarkdown<TranslatedValues> name="translations.body" label="Body (bound)" tabs={tabs} renderEditor={renderEditor} />
    </Form>
  );
};

/** One text per language plus the full store: German holds only an informal text, so its tab edits that one. */
const LanguageTextsSample = () => {
  const [state, setState] = useState<LanguageTextsChange>({
    texts: { en: 'Opening hours', de: 'Deine Öffnungszeiten' },
    store: { 'en::FORMAL': 'Opening hours', 'de::INFORMAL': 'Deine Öffnungszeiten', 'fr::FORMAL': 'Horaires' },
  });
  const [language, setLanguage] = useState('en');
  return (
    <TranslatableLanguageInput
      label="Section title (one text per language)"
      texts={state.texts}
      store={state.store}
      onChange={setState}
      languages={['en', 'de']}
      activeLanguage={language}
      onActiveLanguageChange={setLanguage}
      maxLength={40}
      showCounterFrom={30}
      announceOverLimit
      clearOtherLanguages
      clearLabelVisible
      showEditingLanguage
      onAutoGenerate={() => {}}
      autoGenerateDisabledReason="Write the English text first"
    />
  );
};

