// Server render of the optional props added in 0.3.2: language tabs with one text per language and a per-field edited
// key, the field's counter threshold, clear and editing-language options; table options (body / header classes,
// aria-sort "none", filler track, page-sticky header, hover only on action rows, empty icon); bulk bar options
// (destructive action, toned count, live count, delete hint); filter buttons (data attributes, label, badge class);
// the account menu's avatar node and class; the segmented control's current tone, indicator class and highlighted
// option; the frame's data attributes and styles.
//
// Runs against the installed package (consumer check) or, from the repository, against its own build:
// node test/consumer/fixtures/plain/options-render.mjs
import { createElement as h } from 'react';
import { renderToString } from 'react-dom/server';
import { setTranslations } from '@mgamadeus/ddd-admin-ui/i18n';
import { ClearFiltersButton, EntityListBulkBar, EntityListTable, FilterToggleButton } from '@mgamadeus/ddd-admin-ui/list';
import { SegmentedControl } from '@mgamadeus/ddd-admin-ui/primitives';
import { AdminUiProvider } from '@mgamadeus/ddd-admin-ui/provider';
import { AccountMenu, AppShell } from '@mgamadeus/ddd-admin-ui/shell';
import { TranslatableInput, TranslatableLanguageInput } from '@mgamadeus/ddd-admin-ui/translations';
import { mergeLanguageTabs } from '@mgamadeus/ddd-admin-ui/logic';

setTranslations('en', 'FORMAL', {});
const render = (node) => renderToString(h(AdminUiProvider, {}, node));
const checks = [];

// ── translatable inputs ───────────────────────────────────────────────────────────────────────────────────────────
const languageInput = render(
  h(TranslatableLanguageInput, {
    label: 'Title',
    texts: { en: 'Hello', de: 'Hallo du' },
    store: { 'en::FORMAL': 'Hello', 'de::INFORMAL': 'Hallo du', 'fr::FORMAL': 'Bonjour' },
    onChange: () => {},
    languages: ['en', 'de'],
    activeLanguage: 'de',
    onActiveLanguageChange: () => {},
    maxLength: 100,
    showCounterFrom: 50,
    clearOtherLanguages: true,
    clearLabelVisible: true,
    showEditingLanguage: true,
  }),
);
checks.push(
  ['language input: one tab per offered language, none for a stored language not offered', (languageInput.match(/role="tab"/g) ?? []).length === 2 && !languageInput.includes('>FR<')],
  ['language input: the German tab edits the only (informal) text of this field', languageInput.includes('DE · Informal') && languageInput.includes('value="Hallo du"')],
  ['language input: the editing line names the edited language', languageInput.includes('data-translatable-editing') && languageInput.includes('Editing:')],
  ['language input: the counter waits for its threshold', !languageInput.includes('/ 100')],
  ['language input: "Clear other languages" and a labelled "Clear all"', languageInput.includes('Clear other languages') && languageInput.includes('Clear all</button>')],
);

const tabs = mergeLanguageTabs('en::FORMAL', ['en::FORMAL', 'de::FORMAL'], ['de::INFORMAL'], { editedKeyPerField: true });
const perField = (value) =>
  render(h(TranslatableInput, { label: 'Field', value, onChange: () => {}, locales: tabs, activeLocale: 'de::FORMAL', onActiveLocaleChange: () => {} }));
checks.push(
  ['per-field key: a field with only an informal text edits it', perField({ 'de::INFORMAL': 'Hi' }).includes('value="Hi"')],
  ['per-field key: a field with both edits the formal text', perField({ 'de::INFORMAL': 'Hi', 'de::FORMAL': 'Guten Tag' }).includes('value="Guten Tag"')],
);
const blocked = render(
  h(TranslatableInput, {
    label: 'Field',
    value: {},
    onChange: () => {},
    locales: tabs,
    activeLocale: 'en::FORMAL',
    onActiveLocaleChange: () => {},
    onAutoGenerate: () => {},
    autoGenerateDisabledReason: 'Write the English text first',
  }),
);
checks.push(['AI action disabled with its reason, the field stays editable', blocked.includes('Write the English text first') && /<button[^>]*disabled=""[^>]*>(?:<svg[^]*?<\/svg>)?Auto-translate/.test(blocked) && !/<input[^>]*disabled=""/.test(blocked)]);

// ── table ──────────────────────────────────────────────────────────────────────────────────────────────────────────
const items = [
  { id: 1, name: 'First' },
  { id: 2, name: 'Second' },
];
const fixedColumns = [
  { id: 'name', header: 'Name', cell: (item) => item.name, width: '200px', sortKey: 'name', headerClassName: 'head-only', cellClassName: 'body-only' },
  { id: 'actions', header: 'Actions', cell: () => 'Edit', width: 'content', pin: 'end' },
];
const table = render(
  h(EntityListTable, {
    items,
    getRowKey: (item) => String(item.id),
    columns: fixedColumns,
    onSortChange: () => {},
    sort: null,
    markUnsortedHeaders: true,
    fillWidth: true,
    rowHover: 'action',
    rowAction: (item) => (item.id === 1 ? () => {} : null),
  }),
);
checks.push(
  ['table: aria-sort="none" on a sortable unsorted header', table.includes('aria-sort="none"')],
  ['table: header-only and body-only column classes', (table.match(/head-only/g) ?? []).length === 1 && (table.match(/body-only/g) ?? []).length === 2],
  ['table: a filler track before the trailing end pin', table.includes('minmax(0px, 1fr) max-content') && (table.match(/data-list-filler/g) ?? []).length === 3],
  ['table: only rows with an action tint on hover', (table.match(/\[&amp;:not\(\[data-state=selected\]\):hover\]:bg-transparent/g) ?? []).length === 1],
);
const pageHeader = render(
  h(EntityListTable, { items, getRowKey: (item) => String(item.id), columns: fixedColumns, stickyHeader: 'page', stickyHeaderTop: '4rem' }),
);
checks.push([
  'table: page-sticky header in its own strip over a sideways body scroller',
  pageHeader.includes('data-list-sticky-header') && pageHeader.includes('top:4rem') && /data-entity-list-scroll="true" class="overflow-x-auto overflow-y-hidden"/.test(pageHeader),
]);
const empty = render(h(EntityListTable, { items: [], getRowKey: () => '', columns: fixedColumns, emptyIcon: h('svg', { 'data-empty-icon': '' }) }));
checks.push(['table: the empty state shows its icon', empty.includes('data-empty-icon')]);

// ── bulk bar and filter buttons ────────────────────────────────────────────────────────────────────────────────────
const bulk = render(
  h(EntityListBulkBar, {
    selection: { count: 3, clear: () => {} },
    actions: [{ id: 'archive', label: 'Archive', variant: 'destructive', countClassName: 'count-tone', className: 'own-action', onClick: () => {} }],
    onDelete: () => {},
    deleteHint: 'Locked rows are kept',
    deleteDisabled: true,
    countLive: true,
  }),
);
checks.push(
  ['bulk bar: destructive look, own class and toned count', bulk.includes('own-action') && bulk.includes('text-destructive') && bulk.includes('<span class="count-tone">3</span>')],
  ['bulk bar: the count is a live region', /role="status" aria-live="polite"[^>]*>3 selected/.test(bulk)],
  ['bulk bar: Delete disabled', /disabled=""[^>]*>[^]*Delete \(3\)/.test(bulk)],
);
const filters = render(
  h('div', null, [
    h(FilterToggleButton, { key: 't', open: true, onOpenChange: () => {}, activeFilterCount: 2, 'aria-label': 'Filters (2)', badgeClassName: 'badge-own', badgeInvertWhenOpen: false, 'data-tour': 'filters' }),
    h(ClearFiltersButton, { key: 'c', onClear: () => {}, activeFilterCount: 2, 'data-tour': 'clear' }),
  ]),
);
checks.push(
  ['filter buttons pass data attributes', filters.includes('data-tour="filters"') && filters.includes('data-tour="clear"')],
  ['filter toggle: own name, badge class, no inversion', filters.includes('aria-label="Filters (2)"') && filters.includes('badge-own') && !filters.includes('bg-primary-foreground text-primary')],
);

// ── shell ─────────────────────────────────────────────────────────────────────────────────────────────────────────
const account = render(
  h(AccountMenu, { name: 'Alex Example', entries: [], avatar: h('span', { 'data-own-avatar': '' }, 'icon') }),
);
const accountClass = render(h(AccountMenu, { name: 'Alex Example', entries: [], avatarClassName: 'bg-brand' }));
checks.push(
  ['account menu: an own avatar node', account.includes('data-own-avatar') && !account.includes('>AE<')],
  ['account menu: avatar classes', accountClass.includes('bg-brand ') || accountClass.includes('bg-brand"')],
);
const frame = render(
  h(
    AppShell,
    { navigation: [], 'data-area': 'partner', style: { '--nav-h': '5rem' }, contentStyle: { minHeight: '50vh' }, contentAttributes: { 'data-page': 'x' } },
    h('p', null, 'Page'),
  ),
);
checks.push(['frame: data attributes and styles on the root and <main>', frame.includes('data-area="partner"') && frame.includes('--nav-h:5rem') && /<main[^>]*data-page="x"[^>]*style="min-height:50vh"/.test(frame)]);

// ── segmented control ─────────────────────────────────────────────────────────────────────────────────────────────
const segmented = render(
  h(SegmentedControl, {
    value: 'b',
    onValueChange: () => {},
    'aria-label': 'Period',
    tone: 'current',
    options: [
      { value: 'a', label: 'Day' },
      { value: 'b', label: 'Week' },
    ],
  }),
);
checks.push(
  ['segmented control: the current tone draws from the text colour', segmented.includes('bg-current/10') && segmented.includes('bg-current/20')],
  ['segmented control: the highlighted option carries data-highlighted', /data-state="checked" data-highlighted="true"/.test(segmented)],
);

let failed = false;
for (const [label, passed] of checks) {
  console.log(`${passed ? 'ok     ' : 'FAILED '} ${label}`);
  if (!passed) failed = true;
}
if (failed) process.exit(1);
